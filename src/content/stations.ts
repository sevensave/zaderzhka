/** Что пилот отправляет станции. Цифры подставляет интерфейс. */
export function replyText(
  kind: 'truth' | 'hold' | 'eta' | 'papa',
  name: string,
  info: { late?: string; eta?: string },
): string {
  switch (kind) {
    case 'truth':
      return `«${name}», говорит «Тихоход». Я посчитал. К вам не успеваю: ${info.late ?? 'опоздание'} даже на форсаже. Простите меня.`
    case 'hold':
      return `«${name}», я «Тихоход». Держитесь. Я иду.`
    case 'eta':
      return `«${name}», я «Тихоход». Буду у вас ${info.eta ?? ''}. Дождитесь.`
    case 'papa':
      return `«${name}», я «Тихоход». Тася, позови папу. Мне нужно поговорить с папой.`
  }
}

