// ——— «Колыбель»: показания каждые четыре часа ———
// Давление падает линейно с удара (день 0, 20:00) до 70 кПа в момент конца воздуха.
const K_START = d(0, '20:00')
const K_T = STATION.kolybel.T
export function kPressure(t: number): number {
  return 101.3 - ((101.3 - 70) * (t - K_START)) / (K_T - K_START)
}
function kTemp(t: number): number {
  return Math.max(4, 19 - (t - K_START) * 0.042)
}
function kCharge(t: number): number {
  return Math.max(6, 94 - (t - K_START) * 0.27)
}
const num = (x: number, digits = 1) => x.toFixed(digits).replace('.', ',')

