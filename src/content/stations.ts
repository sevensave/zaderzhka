function kolybelReadings(from: number, to: number, mode: 'base' | 'hold' | 'papa'): BaseLine[] {
  const out: BaseLine[] = []
  let i = 0
  for (let t = d(0, '22:00'); t < to; t += 4, i++) {
    if (t <= from) continue
    const p = num(kPressure(t))
    const temp = Math.round(kTemp(t))
    const charge = Math.round(kCharge(t))
    const night = ((t + 8) % 24 + 24) % 24 < 6
    const head = night ? 'Это Тася, «Колыбель». Ночное чтение, я шёпотом.' : '«Тихоход», это «Колыбель», говорит Тася.'
    let body = `Давление — ${p}. Температура — ${temp}. Заряд — ${charge}. Приём.`
    if (mode === 'hold' && i % 3 === 1) body = `Давление — ${p}. Температура — ${temp}. Заряд — ${charge}. Мы держимся, как вы сказали. Приём.`
    if (mode === 'papa' && i % 5 === 2) body = `Давление — ${p}. Температура — ${temp}. Заряд — ${charge}. Папа сказал, вы с ним говорили. Он теперь всё время улыбается. Приём.`
    const extra = TASYA[i]
    out.push({ at: t, text: extra ? `${head}\n${body}\n${extra}` : `${head}\n${body}` })
  }
  return out
}

