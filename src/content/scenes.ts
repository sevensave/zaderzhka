export function epilogueOpening(kind: EndingKind): string {
  switch (kind) {
    case 'kurs':
    case 'svoy':
      return 'Буксир уходит к «Перевалу». С каждым часом «Порог» дальше.'
    case 'razvorot':
      return 'Буксир идёт к «Порогу». С каждым часом задержка меньше.'
    case 'drift':
      return 'Буксир дрейфует. Задержка растёт.'
  }
}

export function epilogueArrival(kind: EndingKind, saved: number): string {
  switch (kind) {
    case 'kurs':
    case 'svoy':
      return `Двенадцать суток экономом. В рубке тихо, за спиной дышат ${saved === 1 ? 'один человек' : `${saved} человек`}.\n«Перевал». Огни узла. Ты тормозишь, и топливная шкала гаснет до последнего деления.\nВеры в этом счёте нет: её сигнал так и не был отправлен.`
    case 'razvorot':
      return '«Порог» — тёмный силуэт без единого огня.\nДиспетчерский модуль заперт изнутри. Ты открываешь его своим кодом доступа: за шесть лет она его так и не сменила.\nНа пульте иней. В горшке у микрофона — кактус, чёрный и хрупкий, с одним засохшим цветком.\nДинамик громкой связи работает от аварийной батареи. Из него, тихо и по кругу, звучит твой голос: вечерние сообщения, одно за другим.\nТы садишься в её кресло.\nТоплива ноль. До «Перевала» не долетит никто: ни ты, ни те, кто за спиной. Ты знал это, когда разворачивался.'
    case 'drift':
      return 'Последний сигнал доходит через одиннадцать часов. Следующий не доходит совсем.\nВ рубке горит одна янтарная лампа.'
  }
}

