export function porogTurnScene(s: GameState): string {
  const names = s.tug.aboard.map((id) => PEOPLE.find((p) => p.id === id)?.name).filter(Boolean) as string[]
  if (!names.length) {
    return 'Курс: «Порог». Задержка канала начинает падать.\nВ рубке никого, кроме тебя. Некому сказать, что ты делаешь.'
  }
  const day = Math.floor((s.t + 8) / 24) + 1
  const zoyaReads = s.tug.aboard.includes('zoya') && day >= 16
  const reader = zoyaReads ? 'Зоя встаёт у тебя за спиной и вслух, ровно, как сводку, читает' : 'Кто-то из пассажиров встаёт у тебя за спиной и вслух читает'
  return `Курс: «Порог». Задержка канала начинает падать.\n${reader} имена тех, кто на борту:\n${names.join('.\n')}.\n[пауза]\nПотом садится и молчит. Никто не просит тебя развернуться. Это хуже.`
}

