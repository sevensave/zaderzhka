const QUIET: string[] = [
  'В отсеках тихо. Слышно, как гудит регенератор.',
  'Пассажиры спят по очереди: так меньше расход воздуха. Их никто не учил, они сами.',
  'За спиной разговаривают вполголоса. Когда ты оборачиваешься, замолкают.',
]

export function boardFor(s: GameState, day: number): string[] {
  const aboard = new Set(s.tug.aboard)
  if (!aboard.size) return []
  const out = ENTRIES.filter((e) => e.day === day && e.need.every((n) => aboard.has(n))).map((e) => `День ${day}. ${typeof e.text === 'function' ? e.text(s) : e.text}`)
  if (!out.length && day % 3 === 0) out.push(`День ${day}. ${QUIET[(day / 3) % QUIET.length]}`)
  return out
}

/** Строка в списке пассажиров. Меняется по дням. */
export function personStatus(s: GameState, id: string): string | null {
  const day = Math.floor((s.t + 8) / 24) + 1
  if (id === 'zoya') {
    if (day < 8) return 'медотсек, без сознания'
    if (day < 16) return 'медотсек, в сознании, не говорит'
    return 'в рубке'
  }
  if (id === 'lida') return 'медотсек, шина на бедре'
  return null
}
