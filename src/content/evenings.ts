export function eveningOptions(s: GameState, day: number): EveningLine[] {
  const toKolybel = s.tug.flight?.to === 'kolybel' || s.tug.at === 'kolybel' || s.st.kolybel.rescued
  const all = EVENINGS[day] ?? []
  const ok = all.filter((o) => {
    switch (o.when) {
      case 'klyuchAboard':
        return s.st.klyuch.rescued
      case 'notKlyuchAboard':
        return !s.st.klyuch.rescued
      case 'eleven':
        return s.tug.aboard.length === 11
      case 'notEleven':
        return s.tug.aboard.length !== 11
      case 'five':
        return s.tug.aboard.length === 5
      case 'revealed':
        return s.vera.revealed
      case 'hidden':
        return !s.vera.revealed
      case 'toKolybel':
        return toKolybel
      case 'notKolybel':
        return !toKolybel
      case 'channelOff':
        return s.vera.revealed && !s.vera.channelOn
      default:
        return true
    }
  })
  return ok.slice(0, 4)
}

export function eveningText(id: string | null): string | null {
  if (!id) return null
  for (const day of Object.values(EVENINGS)) {
    const o = day.find((x) => x.id === id)
    if (o) return o.text
  }
  return null
}

